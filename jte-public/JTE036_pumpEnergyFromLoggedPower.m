function R=JTE036_pumpEnergyFromLoggedPower(t,powerB_W,powerS_W,opts)
% Optional POSTPROCESSOR. Requires independently logged, audited Pump_power_calc outputs.
% Do not infer pump power from jteUcore (pre-filter FlwR_calc command).
if nargin~=4 || ~isstruct(opts) || ~isscalar(opts)
 error('JTE036:Config','Pass opts with proven provenance and sample semantics');
end
assert(isfield(opts,'pumpPowerOutputVerified') && islogical(opts.pumpPowerOutputVerified) ...
  && isscalar(opts.pumpPowerOutputVerified) && opts.pumpPowerOutputVerified,...
  'JTE036:PumpPowerProvenanceRequired');
assert(isfield(opts,'sampling') && ischar(opts.sampling),...
  'JTE036:SamplingSemanticsRequired');
t=double(t(:));pB=double(powerB_W(:));pS=double(powerS_W(:));
assert(numel(t)>=2 && numel(t)==numel(pB) && numel(t)==numel(pS) ...
  && all(isfinite(t)) && all(diff(t)>0) ...
  && all(isfinite(pB)) && all(isfinite(pS)) ...
  && all(pB>=0) && all(pS>=0), 'JTE036:InvalidLoggedPower');
switch opts.sampling
 case 'verified_zoh'
   eb=sum(diff(t).*pB(1:end-1));
   es=sum(diff(t).*pS(1:end-1));
 case 'verified_continuous_linear'
   eb=trapz(t,pB);es=trapz(t,pS);
 otherwise
   error('JTE036:SamplingSemanticsRequired',...
      'No interpolation/integration without verified sample semantics');
end
R=struct('energyBaseline_J',eb,'energyStudy_J',es,...
   'deltaEnergy_J',es-eb,...
   'source','independently logged physical pump power',...
   'interpretation','MathWorks model pump estimate, not measured EV energy');
end
