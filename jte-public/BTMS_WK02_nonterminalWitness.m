function w = BTMS_WK02_nonterminalWitness(s, processedPriorTop, finalstep, pin)
% WK02 SOURCE-ONLY candidate. Caller captures prior top BEFORE step(s).
% This function NEVER treats a terminal step or callback as accepted major.
assert(islogical(finalstep)&&isscalar(finalstep)&&~finalstep,...
 'WK02:TerminalNotMajor','Terminal step belongs only to a separate receipt.');
assert(isnumeric(processedPriorTop)&&isscalar(processedPriorTop)&&...
 isfinite(processedPriorTop),'WK02:PriorClock','Prior top unavailable.');
assert(isstruct(pin)&&isfield(pin,'model')&&isfield(pin,'sourceSHA')&&...
 isfield(pin,'cloneExpectedSHA')&&isfield(pin,'cloneActualSHA')&&...
 isfield(pin,'privateReadbackVerified'),'WK02:Provenance','Missing source/clone pin.');
assert(strcmp(pin.sourceSHA,'0a61b958173e55f9a5683d8f91fc82dc00078d6a948b66c23883b370bbc4abc0'),...
 'WK02:SourceSHA','Wrong vendor source.');
assert(ischar(pin.cloneExpectedSHA)&&~isempty(regexp(pin.cloneExpectedSHA,'^[a-f0-9]{64}$','once'))&&...
 strcmp(pin.cloneExpectedSHA,pin.cloneActualSHA)&&...
 isequal(pin.privateReadbackVerified,true),'WK02:CloneSHA','Clone SHA/readback not qualified.');
configuredMode=get_param(pin.model,'SimulationMode');
assert(strcmp(configuredMode,'normal'),'WK02:Mode','Nonterminal candidate requires normal mode.');
assert(strcmp(s.Status,'paused')&&isnumeric(s.Time)&&isscalar(s.Time)&&...
 isfinite(s.Time)&&s.Time>=processedPriorTop,...
 'WK02:NextTop','A nonterminal step must pause at finite next top.');
% Existing helper verifies bounded four-role native signal clocks, widths,
% actual pre-update DState/output at its own tick and no tail growth.
q=BTMS_M3_completed(s,processedPriorTop,false,NaN);
e=q.phases;
assert(numel(e)==3&&all(cellfun(@(v)~isempty(v)&&v.readable,e)),...
 'WK02:Phases','Missing readable actuator phases.');
assert(e{1}.phase==1&&e{2}.phase==2&&e{3}.phase==3&&...
 e{1}.sequence<e{2}.sequence&&e{2}.sequence<e{3}.sequence&&...
 e{1}.time==e{2}.time&&e{2}.time==e{3}.time&&...
 e{1}.state==e{2}.state,...
 'WK02:PhaseOrder','Phase/order/preupdate state mismatch.');
% Phase 3 is the observed postupdate state. Do not infer a solver step from
% callback time or apply an unverified arithmetic recurrence tolerance.
o=s.SimulationOutput;
assert(isempty(o.ErrorMessage),'WK02:SimulationError','Output reports error.');
w=struct('processedPriorTop',processedPriorTop,'finalstep',false,...
 'Status',char(s.Status),'returnedTime',s.Time,...
 'fourSignalTailClocks',q.signalTimes,'core',q.core,'held',q.held,...
 'actuatorOutput',q.y,'Ttrue312',q.T312,...
 'preState',e{1}.state,'preOutput',e{1}.output,...
 'preUpdateState',e{2}.state,'preUpdateInput',e{2}.input,...
 'postState',e{3}.state,'phaseTimes',[e{1}.time,e{2}.time,e{3}.time],...
 'phaseSequence',[e{1}.sequence,e{2}.sequence,e{3}.sequence],...
 'configuredSimulationMode',configuredMode,...
 'sourceSHA',pin.sourceSHA,'cloneSHA',pin.cloneActualSHA,...
 'scope','Completed NONTERMINAL major only. Four clocks are bounded signal tails, not full ToFile. Hidden physical t0 not certified.');
end
