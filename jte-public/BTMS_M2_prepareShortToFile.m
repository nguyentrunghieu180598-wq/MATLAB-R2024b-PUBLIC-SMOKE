function proof = BTMS_M2_prepareShortToFile(sourceFile, derivativeFile, privateDir)
% BTMS M2: static preparation ONLY; no sim(), initialize(), compile or run.
% Isolated instrumentation copy for the already compiled amended 10/5ms
% model. Exactly 4 streaming To File taps. NO editing source/vendor model.
% REQUIRED: independent full-graph static review and R2024b compile before
% any prospective MATLAB plant authorization. Not an accepted G5 result.
assert(strcmp(version('-release'),'2024b') && ...
       contains(version,'24.2.0.3361896'), ...
       'M2:WrongMATLAB','Pinned MATLAB R2024b Update10 is required.');
assert(isfile(sourceFile) && ~isfile(derivativeFile) && ...
       isfolder(privateDir), 'M2:Paths', ...
       'Existing source, NEW derivative, existing private directory required.');
assert(exist('JTE2026sha256','file')==2, 'M2:MissingSHA', ...
       'Work validated SHA function is required.');
srcHash=JTE2026sha256(sourceFile);
assert(copyfile(sourceFile,derivativeFile)==1,'M2:Copy', ...
       'Cannot copy source to new isolated derivative.');
[~,m]=fileparts(derivativeFile);
load_system(derivativeFile);
cleaner=onCleanup(@()close_system(m,0)); %#ok<NASGU>
bc=[m '/Battery Control'];
ctrl=[bc '/FlwR_calc'];
hold=[bc '/Amended command sample hold'];
act=[bc '/Amended sampled actuator'];
assert(getSimulinkBlockHandle(ctrl)>0 && ...
       getSimulinkBlockHandle(hold)>0 && ...
       getSimulinkBlockHandle(act)>0, ...
       'M2:Amendment','Expected frozen sampled model structure missing.');
assert(strcmp(get_param(hold,'BlockType'),'ZeroOrderHold') && ...
       strcmp(get_param(act,'BlockType'),'DiscreteStateSpace'), ...
       'M2:Amendment','Expected compiled primitive blocks have changed.');
Ts=str2double(get_param(act,'SampleTime'));
assert(any(Ts==[0.01,0.005]) && ...
       str2double(get_param(hold,'SampleTime'))==Ts, ...
       'M2:SamplePeriod','Only the pre-registered 10ms or 5ms allowed.');
alpha=exp(-Ts/0.001);
assert(abs(str2double(get_param(act,'A'))-alpha)<=8*eps(1) && ...
       abs(str2double(get_param(act,'B'))-(1-alpha))<=8*eps(1) && ...
       str2double(get_param(act,'C'))==1 && ...
       str2double(get_param(act,'D'))==0, ...
       'M2:Law','A/B/C/D differs from frozen sampled-actuator law.');
assert(strcmp(get_param(m,'Solver'),'ode23t') && ...
       str2double(get_param(m,'MaxStep'))==0.05, ...
       'M2:Solver','Do not change original solver policy.');
cp=get_param(ctrl,'PortHandles');
hp=get_param(hold,'PortHandles');
ap=get_param(act,'PortHandles');
assert(numel(cp.Outport)==1 && numel(hp.Outport)==1 && ...
       numel(ap.Outport)==1 && ...
       upstream(hp.Inport(1))==cp.Outport(1) && ...
       upstream(ap.Inport(1))==hp.Outport(1), ...
       'M2:InputWiring','Frozen command/hold/actuator chain differs.');
sinks=find_system(m,'LookUnderMasks','all','FollowLinks','on', ...
                  'BlockType','ToWorkspace');
tt={};
for k=1:numel(sinks)
 if strcmp(get_param(sinks{k},'VariableName'),'jteTtrue')
  tt{end+1}=sinks{k}; %#ok<AGROW>
 end
end
assert(numel(tt)==1,'M2:TrueT','One canonical jteTtrue sink required.');
tp=get_param(tt{1},'PortHandles');
ttrueSource=upstream(tp.Inport(1));
assert(ttrueSource~=-1,'M2:TrueT','Missing existing T312 source.');
names={'uCore','uSampled','actuatorY','Ttrue312'};
ports={cp.Outport(1),hp.Outport(1),ap.Outport(1),ttrueSource};
assert(numel(unique(names))==4);
oldTSource=ttrueSource;
oldCtrl=upstream(hp.Inport(1));oldHeld=upstream(ap.Inport(1));
configKeys={'Solver','SolverType','RelTol','AbsTol','MaxStep', ...
            'LoadInitialState','StartTime','StopTime'};
configBefore=cellfun(@(k)get_param(m,k),configKeys,'UniformOutput',false);
paths=cell(1,4);outputs=cell(1,4);
for k=1:4
 src=ports{k};
 srcBlock=get_param(src,'Parent');
 parent=get_param(srcBlock,'Parent');
 label=['BTMS_M2_' names{k}];
 path=[parent '/' label];
 file=fullfile(privateDir,[m '_' names{k} '.mat']);
 assert(getSimulinkBlockHandle(path)==-1 && ~isfile(file), ...
        'M2:NoOverwrite', ...
        'Logger or target already exists; never overwrite existing evidence.');
 add_block('simulink/Sinks/To File',path, ...
  'FileName',file,'MatrixName',['btmsM2_' names{k}], ...
  'SaveFormat','Timeseries','Decimation','1','SampleTime','-1');
 ph=get_param(path,'PortHandles');
 add_line(parent,src,ph.Inport(1),'autorouting','on');
 assert(upstream(ph.Inport(1))==src,'M2:Tap', ...
        'To File is not connected to the intended source output.');
 paths{k}=path;outputs{k}=file;
end
assert(upstream(hp.Inport(1))==oldCtrl && ...
       upstream(ap.Inport(1))==oldHeld && ...
       upstream(tp.Inport(1))==oldTSource, ...
       'M2:OriginalWiring','An original data path was altered.');
configAfter=cellfun(@(k)get_param(m,k),configKeys,'UniformOutput',false);
assert(isequal(configBefore,configAfter),'M2:Config', ...
       'No original model configuration parameter may change.');
save_system(m,derivativeFile);
assert(strcmp(srcHash,JTE2026sha256(sourceFile)),'M2:SourceMutated', ...
       'Immutable source file was altered.');
proof=struct('scope','STATIC_ONLY_NO_SIMULATION', ...
 'sourceSHA256',srcHash, ...
 'instrumentedModelSHA256',JTE2026sha256(derivativeFile), ...
 'period_s',Ts,'names',{names},'loggerBlockPaths',{paths}, ...
 'privateLogPaths',{outputs},'sourceSolverUnchanged',true, ...
 'originSignalEdgesPreserved',true,'newStreamingTaps',4, ...
 'MATLABRuntime',version,'allNativeClocksPreservedByDesign',false, ...
 'trueT312CompiledWidthVerified',false,'initialPhysicalStateVerified',false, ...
 'acceptedMajorStateVerified',false,'loggingRuntimeRAMVerified',false, ...
 'G5_ACCEPTED',false, ...
 'nextGate','Independent R2024b compile/graph+ToFile time/phase validation; no plant is authorized.');
fprintf('BTMS_M2_STATIC_4_TO_FILE_TAPS_PREPARED; compile=0 sim=0 G5=0\n');
end
function p=upstream(port)
l=get_param(port,'Line');assert(l~=-1,'M2:MissingLine','Input disconnected.');
p=get_param(l,'SrcPortHandle');assert(p~=-1, ...
 'M2:MissingSource','Input source port missing.');
end
